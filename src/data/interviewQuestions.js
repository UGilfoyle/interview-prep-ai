/**
 * Helper to get a curated question for a track, category, role, and company
 */
export function getCuratedQuestionForTrack(track, category, role = '', company = '') {
  const matchingTrackAndCat = CURATED_INTERVIEW_QUESTIONS.filter(
    (q) => q.track === track && q.category === category
  );

  if (matchingTrackAndCat.length > 0) {
    const compLower = (company || '').toLowerCase();
    const roleLower = (role || '').toLowerCase();
    const tailored = matchingTrackAndCat.find((q) =>
      q.companyMatch.some((tag) => compLower.includes(tag) || roleLower.includes(tag))
    );
    return tailored || matchingTrackAndCat[Math.floor(Math.random() * matchingTrackAndCat.length)];
  }

  // Fallback to any question in the track
  const trackQuestions = CURATED_INTERVIEW_QUESTIONS.filter((q) => q.track === track);
  return trackQuestions.length > 0
    ? trackQuestions[0]
    : CURATED_INTERVIEW_QUESTIONS[0];
}
